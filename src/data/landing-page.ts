function getFactoryPublicCode(name: string) {
  return (
    name
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .replace(/Đ/g, "D")
      .replace(/đ/g, "d")
      .replace(/[^A-Za-z]/g, "")
      .slice(-3)
      .toUpperCase() || "XXX"
  );
}

